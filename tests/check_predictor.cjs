const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const engine=require('../docs/predictor-engine.js');
const artifact=JSON.parse(fs.readFileSync(path.join(root,'docs/data/predictor.json'),'utf8'));
const fixtures=JSON.parse(fs.readFileSync(path.join(root,'results/predictor/parity_fixtures.json'),'utf8'));
let maximumDifference=0;
for(const fixture of fixtures) {
  const actual=engine.predict(fixture.input,artifact);
  const difference=Math.abs(actual.purchase_score-fixture.score);
  maximumDifference=Math.max(maximumDifference,difference);
  assert.ok(difference<1e-12,`${fixture.name}: Python ${fixture.score}, JS ${actual.purchase_score}`);
  assert.equal(actual.predicted_label,Number(fixture.score>=artifact.threshold));
  if(artifact.inference.kind!=='logistic') assert.ok(Math.abs(actual.base_score+Object.values(actual.contributions).reduce((a,b)=>a+b,0)-actual.purchase_score)<1e-12,'Contributions must explain the actual score');
}
const input=fixtures.at(-2).input;
