for(const bad of [{...input,product_pages:-1},{...input,product_pages:1.5},{...input,product_seconds:'NaN'},{...input,weekend:''},{...input,visitor_type:''},{...input,product_pages:'0x10'},{...input,product_pages:0,product_seconds:1}]) assert.throws(()=>engine.predict(bad,artifact));
